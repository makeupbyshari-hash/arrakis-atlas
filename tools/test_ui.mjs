import { chromium } from 'playwright-core';
import { readFileSync, writeFileSync, unlinkSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const assets = join(root,'app/src/main/assets');
const original = readFileSync(join(assets,'index.html'),'utf8');
const preview = join(assets,'test-view.html');
writeFileSync(preview,original.replaceAll('file:///android_asset/tiles/','tiles/'),'utf8');
const bins=['/usr/bin/google-chrome','/usr/bin/google-chrome-stable','/usr/bin/chromium','/usr/bin/chromium-browser'];
let binary=bins.find(existsSync);
if(!binary)throw new Error('No Chrome or Chromium browser on runner');
const browser=await chromium.launch({executablePath:binary,headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
try{
 const page=await browser.newPage({viewport:{width:412,height:870},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 const errs=[];
 page.on('pageerror',e=>errs.push(e.message));
 await page.goto(pathToFileURL(preview).href);
 await page.locator('#mapframe').waitFor();
 assert.equal(await page.locator('#pins .pin').count(),0,'Map must initially be uncluttered');
 await page.locator('#search').fill('Industrie');
 assert.ok((await page.locator('#suggestions .suggest').count())>0,'No item suggestions');
 await page.locator('#suggestions .suggest').filter({hasText:'Industriepumpe'}).first().click();
 assert.equal(await page.locator('#search').inputValue(),'Industriepumpe','Suggestion must fill full selected item');
 assert.ok((await page.locator('#selectionBar').innerText()).includes('Industriepumpe'),'Selected item not shown');
 assert.ok((await page.locator('#spotList .spot').count())>=3,'All relevant Industrial Pump sources not listed');
 assert.equal(await page.locator('#pins .pin').count(),2,'Expected exactly two approximate pinned industrial pump sources (Sentinel and Zoe)');
 let summary=(await page.locator('#selectionBar').innerText());
 assert.ok(summary.includes('2 ungefähr markierte Orte'),summary);
 await page.locator('#plus').click({clickCount:5,delay:40});
 const count=await page.locator('#tilelayer .tile').count();
 assert.ok(count>0&&count<80,'Tiles failed to load efficiently: '+count);
 const highRes=await page.locator('#tilelayer .tile').evaluateAll(arr=>arr.some(x=>x.src.includes('/4/')));
 assert.ok(highRes,'Map zoom did not switch to highest map tiles');
 await page.locator('#reset').click();
 await page.locator('#search').fill('Komplex');
 await page.locator('#suggestions .suggest').filter({hasText:'Komplexe Maschinen'}).first().click();
 assert.equal(await page.locator('#search').inputValue(),'Komplexe Maschinen');
 assert.ok((await page.locator('#spotList .spot').count())>=4,'Multiple ironworks + unpinned sources expected');
 assert.equal(await page.locator('#pins .pin').count(),3,'Three distinct Ironworks regions must be pinned');
 await page.locator('#spotList .spot').first().click();
 assert.equal(await page.locator('#details').isVisible(),true,'Spot details must open');
 await page.locator('#detailClose').click();
 assert.equal(await page.locator('#details').isVisible(),false);
 await page.screenshot({path:join(root,'ui-checked.png')});
 assert.deepEqual(errs,[], 'JavaScript runtime errors: '+errs.join('; '));
 console.log('PASS: selected item filled, item-specific map, 3+ farming sources, detailed tile zoom, details, no JS exceptions');
} finally {
 await browser.close();
 unlinkSync(preview);
}
